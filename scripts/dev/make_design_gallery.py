"""The design gallery (TODO DS7): one page that shows every composition, application screen, design system and template of the ui-design-quality skill with its picture.

    python scripts/dev/make_design_gallery.py

Reads the catalogue (assets/catalogue.json) and the reference pictures (assets/preview) and writes docs/DESIGN_GALLERY.md, with the catalogue id, the one-line summary, the moods and
what to use it for, so a person can browse what DebCraft starts from. Re-run after the catalogue or the pictures change."""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SKILL = REPO / "src" / "forge" / "skills" / "ui-design-quality"
PREVIEW = SKILL / "assets" / "preview"
OUT = REPO / "docs" / "DESIGN_GALLERY.md"
RELATIVE = "../src/forge/skills/ui-design-quality/assets/preview"
GROUPS: list[tuple[str, str, str]] = [
    (
        "Page compositions (marketing pages)",
        "lay-",
        "Seven complete layouts with drawn art; a candidate design names one as `composition: lay-...`.",
    ),
    (
        "Application screens, plain HTML",
        "app-",
        "Twenty-four dashboards, tables, forms, settings and web-app screens; `composition: app-...`. The React versions (`app-react-*`) are the same screens.",
    ),
    (
        "Design systems (tokenised starting points)",
        "ds-",
        "Fourteen DESIGN.md starting points with a specimen picture each.",
    ),
    (
        "Templates",
        "tpl-",
        "Complete landing-page templates (Vite, React, Tailwind) with their own palettes and offline fonts.",
    ),
]


def picture(asset_id: str) -> list[tuple[str, str]]:
    found = []
    for label, suffixes in (("desktop", ("desktop", "specimen")), ("phone", ("phone", "mobile"))):
        for suffix in suffixes:
            if (PREVIEW / f"{asset_id}-{suffix}.jpg").is_file():
                found.append((label, f"{RELATIVE}/{asset_id}-{suffix}.jpg"))
                break
    return found


def main() -> int:
    catalogue = json.loads((SKILL / "assets" / "catalogue.json").read_text(encoding="utf-8"))
    assets = {a["id"]: a for a in catalogue["assets"]}
    lines = [
        "# Design gallery",
        "",
        "What DebCraft starts from when it designs a page or an application screen. Generated by `scripts/dev/make_design_gallery.py` from the asset catalogue; the pictures are real renderings in Edge",
        "(desktop 1280 px, phone 375 px). Nothing here is shipped as it is: the model replaces the tokens, the words and the numbers.",
        "",
    ]
    for title, prefix, blurb in GROUPS:
        members = sorted(a for a in assets if a.startswith(prefix) and not a.startswith("app-react-"))
        if not members:
            continue
        lines += [f"## {title} ({len(members)})", "", blurb, ""]
        for asset_id in members:
            asset = assets[asset_id]
            lines.append(f"### `{asset_id}`: {asset['title'].split(': ', 1)[-1]}")
            lines.append("")
            lines.append(f"{asset['summary']}")
            lines.append("")
            facts = [
                f"moods: {', '.join(asset.get('moods', []))}",
                f"density: {asset.get('density', '')}",
                f"for: {', '.join(asset.get('products', [])[:6])}",
            ]
            lines.append("*" + "; ".join(f for f in facts if not f.endswith(": ")) + "*")
            lines.append("")
            pictures = picture(asset_id)
            if pictures:
                lines.append(" ".join(f"[![{asset_id} {label}]({path})]({path})" for label, path in pictures))
                lines.append("")
    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)} with {sum(1 for line in lines if line.startswith('### '))} entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
