"""Copies a table's shape and rows from a database DebCraft may only read into its own scratch schema (D-568).

To try a change against a running copy of the user's application, the application needs its data: the agents,
the tools registered for them, their settings. The development database is shared (a change there needs the
user's approval each time, D-608), so the rows
are copied into the scratch schema of DebCraft's own database and the application copy is pointed there.
Rows go from one connection to the other with COPY: they never pass through the model. Tables that hold
credentials are refused, like every other read of them.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from psycopg import sql

from forge.config import Secrets
from forge.db.connection import DbTarget, connect, safe_schema_name
from forge.db.scratch import ScratchError, ScratchSchema
from forge.safety.sql_guard import check_read_only

MAX_COPY_ROWS = 50_000
INTEGER_TYPES = ("smallint", "integer", "bigint")
COLUMNS_SQL = """
SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
       pg_get_expr(d.adbin, d.adrelid), t.typtype, n.nspname, a.attidentity
FROM pg_attribute a
JOIN pg_type t ON t.oid = a.atttypid
JOIN pg_namespace n ON n.oid = t.typnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = %s::regclass AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum
"""
PRIMARY_KEY_SQL = """
SELECT a.attname FROM pg_index i
JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
WHERE i.indrelid = %s::regclass AND i.indisprimary
ORDER BY array_position(i.indkey, a.attnum)
"""


@dataclass
class CopyResult:
    table: str
    rows: int
    columns: list[str]
    as_text: list[str] = field(
        default_factory=list
    )  # columns whose own type does not exist in the scratch database
    numbered: list[str] = field(
        default_factory=list
    )  # columns that keep counting on from the highest copied value
    capped: bool = False


@dataclass
class _Column:
    name: str
    kind: str
    not_null: bool
    counts: bool  # filled by a sequence or identity in the source


def _columns(
    source: DbTarget, secrets: Secrets, qualified: str
) -> tuple[list[_Column], list[str], list[str]]:
    with connect(source, secrets, read_only=True) as connection:
        found = connection.execute("SELECT to_regclass(%s)", (qualified,)).fetchone()
        if found is None or found[0] is None:
            return [], [], []
        rows = connection.execute(COLUMNS_SQL, (qualified,)).fetchall()
        key = [row[0] for row in connection.execute(PRIMARY_KEY_SQL, (qualified,)).fetchall()]
    columns: list[_Column] = []
    as_text: list[str] = []
    for name, kind, not_null, default, type_kind, namespace, identity in rows:
        own_type = type_kind in ("e", "c", "d") or namespace != "pg_catalog"  # an enum, a composite, a domain
        if own_type:
            as_text.append(name)
        counts = bool(identity) or str(default or "").startswith("nextval(")
        columns.append(
            _Column(name, "text" if own_type else kind, bool(not_null), counts and kind in INTEGER_TYPES)
        )
    return columns, key, as_text


def copy_table(
    scratch: ScratchSchema,
    source: DbTarget,
    source_schema: str,
    table: str,
    where: str = "",
    limit: int = MAX_COPY_ROWS,
) -> CopyResult:
    """Creates `table` in the scratch schema with the source's columns and primary key and fills it with the
    source's rows (those matching `where`, at most `limit`). An earlier copy of the same table is replaced."""
    schema, name = safe_schema_name(source_schema), safe_schema_name(table)
    denied = {entry.lower() for entry in scratch.deny_tables}
    if name in denied or f"{schema}.{name}" in denied:
        raise ScratchError(f"{schema}.{name} holds credentials and is never copied.")
    limit = max(1, min(limit, MAX_COPY_ROWS))
    source_table = sql.Identifier(schema, name)
    selection = sql.SQL("SELECT * FROM {}").format(source_table).as_string(None)
    if where.strip():
        selection += f" WHERE {where.strip()}"
    check_read_only(
        selection, scratch.deny_tables
    )  # the filter is the model's text: one read-only statement only
    columns, key, as_text = _columns(source, scratch.secrets, f'"{schema}"."{name}"')
    if not columns:
        raise ScratchError(f"{schema}.{name} was not found, or it has no columns.")

    target_table = sql.Identifier(scratch.schema, name)
    parts = [
        sql.SQL("{} {}{}{}").format(
            sql.Identifier(column.name),
            sql.SQL(column.kind),  # from format_type() or the literal 'text': not user text
            sql.SQL(" GENERATED BY DEFAULT AS IDENTITY") if column.counts else sql.SQL(""),
            sql.SQL(" NOT NULL") if column.not_null and not column.counts else sql.SQL(""),
        )
        for column in columns
    ]
    if key:
        parts.append(sql.SQL("PRIMARY KEY ({})").format(sql.SQL(", ").join(map(sql.Identifier, key))))
    names = sql.SQL(", ").join(sql.Identifier(column.name) for column in columns)
    casted = sql.SQL(", ").join(
        sql.SQL("{}::text").format(sql.Identifier(column.name))
        if column.name in as_text
        else sql.Identifier(column.name)
        for column in columns
    )
    read = sql.SQL("COPY (SELECT {} FROM ({}) AS chosen LIMIT {}) TO STDOUT").format(
        casted, sql.SQL(selection), sql.Literal(limit + 1)
    )
    scratch.claim()
    copied = 0
    with (
        connect(source, scratch.secrets, read_only=True) as reader,
        connect(scratch.target, scratch.secrets) as writer,
    ):
        writer.execute(sql.SQL("DROP TABLE IF EXISTS {}").format(target_table))
        writer.execute(sql.SQL("CREATE TABLE {} ({})").format(target_table, sql.SQL(", ").join(parts)))
        scratch.registry.record(scratch.key, "table", name)
        with (
            reader.cursor().copy(read) as outgoing,
            writer.cursor().copy(sql.SQL("COPY {} ({}) FROM STDIN").format(target_table, names)) as incoming,
        ):
            for row in outgoing.rows():
                if copied < limit:
                    incoming.write_row(row)
                copied += 1
        numbered = [column.name for column in columns if column.counts]
        for (
            column_name
        ) in numbered:  # the next row the application inserts gets a number after the copied ones
            highest = writer.execute(
                sql.SQL("SELECT COALESCE(MAX({}), 0) FROM {}").format(
                    sql.Identifier(column_name), target_table
                )
            ).fetchone()
            writer.execute(
                sql.SQL("ALTER TABLE {} ALTER COLUMN {} RESTART WITH {}").format(
                    target_table,
                    sql.Identifier(column_name),
                    sql.Literal(int(highest[0] if highest else 0) + 1),
                )
            )
    return CopyResult(
        table=name,
        rows=min(copied, limit),
        columns=[column.name for column in columns],
        as_text=as_text,
        numbered=numbered,
        capped=copied > limit,
    )
